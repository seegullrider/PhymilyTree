const fs=require('node:fs');
const {DatabaseSync}=require('node:sqlite');
const db=new DatabaseSync('检索队列.sqlite',{readOnly:true});
const id='d46814a3';
const {filename}=db.prepare('select filename from records where id=?').get(id);
const audit=JSON.parse(db.prepare('select details_json from manual_audit_events where record_id=? order by recorded_at desc,rowid desc limit 1').get(id).details_json);
db.close();
const url='https://physics.berkeley.edu/people/faculty/joseph-orenstein';
const file='../人物/'+filename+'.md';
const old='MIT 博士后于1981年加入 Bell Labs 担任研究员。';
const replacement='获 MIT 物理学博士学位，1981 年加入 Bell Labs 任 Member of the Technical Staff，后任 Distinguished MTS。';
const body=fs.readFileSync(file,'utf8');
if(body.split(old).length!==2)throw Error('旧表述不唯一');
audit.audit_id='pi_archive_20261110_1906_'+id;
audit.aspects.postdoc.sources=[...new Set([url,...audit.aspects.postdoc.sources])];
audit.aspects.postdoc.note+=' Berkeley 物理系原页列 MIT 物理博士和 1981 年 Bell Labs MTS 任用，已核公开履历未见独立博士后聘任。';
audit.followup_required=true;
fs.writeFileSync('20261110_1906_Orenstein_人工.json',JSON.stringify(audit,null,2),'utf8');
fs.writeFileSync(file,body.replace(old,replacement),'utf8');
